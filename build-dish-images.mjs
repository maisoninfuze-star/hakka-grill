/**
 * Downloads the kitchen's own photograph for every menu item and encodes
 * card-sized derivatives.
 *
 * The ordering system stores one photo per dish, but several dishes share a
 * frame (a large and a small serving of the same thing, a burger sold single or
 * as a trio). Images are therefore keyed by a hash of the source URL and encoded
 * once, with a separate slug -> key map, so a shared photo costs one file rather
 * than four.
 *
 *   node build-dish-images.mjs            # fetch anything not already cached
 *   node build-dish-images.mjs --refetch  # re-download everything
 */
import sharp from 'sharp';
import fs from 'fs';
import crypto from 'crypto';

const CACHE = 'src-assets/dish';
const OUT = 'public/img/dish';
const WIDTHS = [860, 560, 360];

fs.mkdirSync(CACHE, { recursive: true });
fs.mkdirSync(OUT, { recursive: true });

const src = fs.readFileSync('lib/menu-data.ts', 'utf8');
const MENU = JSON.parse(src.match(/export const MENU: Category\[\] = ([\s\S]*?) as unknown as Category\[\];/)[1]);
const items = MENU.flatMap((c) => c.items);

const key = (url) => crypto.createHash('sha1').update(url).digest('hex').slice(0, 10);

// url -> { key, dishes[] }
const byUrl = new Map();
for (const d of items) {
  if (!d.photo) continue;
  if (!byUrl.has(d.photo)) byUrl.set(d.photo, { key: key(d.photo), dishes: [] });
  byUrl.get(d.photo).dishes.push(d.slug);
}

const refetch = process.argv.includes('--refetch');
const manifest = {};   // imageKey -> { widths, w, h, blur }
const map = {};        // dishSlug -> imageKey
let fetched = 0, cached = 0, skipped = [];

for (const [url, { key: k, dishes }] of byUrl) {
  const file = `${CACHE}/${k}.jpg`;
  if (refetch || !fs.existsSync(file)) {
    const r = await fetch(url);
    if (!r.ok) { skipped.push({ k, status: r.status }); continue; }
    fs.writeFileSync(file, Buffer.from(await r.arrayBuffer()));
    fetched++;
  } else cached++;

  const meta = await sharp(file).rotate().metadata();
  // Portrait sources (the mocktails) get centre-cropped to the card ratio so
  // one grid does not end up with wildly different card heights.
  const target = 5 / 4;
  const isPortrait = meta.width / meta.height < 1;
  const pipeline = () => {
    const p = sharp(file).rotate();
    if (!isPortrait) return p;
    const h = Math.round(meta.width / target);
    return p.extract({ left: 0, top: Math.round((meta.height - h) / 2), width: meta.width, height: Math.min(h, meta.height) });
  };

  const natural = meta.width;
  const widths = [...new Set(WIDTHS.map((w) => Math.min(w, natural)))].sort((a, b) => b - a);
  for (const w of widths) {
    await pipeline().resize({ width: w }).avif({ quality: 55, effort: 4 }).toFile(`${OUT}/${k}-${w}.avif`);
    await pipeline().resize({ width: w }).webp({ quality: 78 }).toFile(`${OUT}/${k}-${w}.webp`);
  }
  const probe = await sharp(`${OUT}/${k}-${widths[0]}.webp`).metadata();
  const blur = await pipeline().resize({ width: 16 }).webp({ quality: 40 }).toBuffer();
  manifest[k] = { widths, w: probe.width, h: probe.height, blur: `data:image/webp;base64,${blur.toString('base64')}` };
  for (const d of dishes) map[d] = k;
}

const ts = `// AUTO-GENERATED by build-dish-images.mjs — do not edit by hand.
// One entry per unique photograph; several dishes can point at the same key.
import type { ImageMeta } from './images';
export const DISH_IMAGES: Record<string, ImageMeta> = ${JSON.stringify(manifest, null, 1)};
export const DISH_IMAGE_OF: Record<string, string> = ${JSON.stringify(map, null, 1)};
`;
fs.writeFileSync('lib/dish-images.ts', ts);

console.log(`unique photos: ${byUrl.size}  (fetched ${fetched}, cached ${cached})`);
console.log(`dishes mapped: ${Object.keys(map).length} of ${items.length}`);
if (skipped.length) console.log('FAILED:', skipped);
